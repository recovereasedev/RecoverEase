/** A list with one item moved one place up (-1) or down (+1). */
function moved<T>(items: readonly T[], index: number, by: -1 | 1): T[] {
  const next = [...items]
  const [item] = next.splice(index, 1)
  next.splice(index + by, 0, item!)
  return next
}

/**
 * Module 5.7 for the doctor (migrations 45, 56): a plan's recovery roadmap on
 * the patient's record, to monitor. Its phases are generated by the
 * database - Initial Recovery, one Recovery and Monitoring phase per goal,
 * Follow-up and Assessment - so there is nothing here to add, rename, move
 * or archive a phase with. The doctor sees each goal's status as the patient
 * records it (or as missed, by the system), assigns and orders the
 * activities in each phase, sees what the patient marked done and when, and
 * chooses the plan's follow-up appointment.
 *
 * Every change is the database's to allow: only the patient's assigned,
 * active doctor may make one (`is_my_patient`), dates must sit inside the
 * plan's, and nothing is deleted - an activity is archived, so the record of
 * what was done outlives it.
 */
export function RoadmapEditor({ patientId, plan }: { patientId: string; plan: PlanWithGoals }) {
  const queryKeys = useQueryKeys()
  const roadmapQuery = useRoadmap(patientId, [plan], { live: true })
  // The clinic's day, as the patient's roadmap counts it - not this device's.
  const zoneQuery = useQuery({
    queryKey: queryKeys.ownClinic.timeZone(),
    queryFn: fetchOwnClinicTimeZone,
  })
  const zone = zoneQuery.data ?? deviceTimeZone()
  const today = todayIn(zone, new Date(useNow()))
  const appointmentsQuery = useQuery({
    queryKey: queryKeys.appointments.forPatient(patientId),
    queryFn: () => fetchAppointments(patientId),
    enabled: Boolean(patientId),
  })
  const appointments = appointmentsQuery.data ?? []
  const followUp = followUpAppointment(plan, appointments)

  const createActivity = useCreateActivity(patientId)
  const updateActivity = useUpdateActivity(patientId)
  const archiveActivity = useArchiveActivity(patientId)
  const restoreActivity = useRestoreActivity(patientId)
  const reorderActivities = useReorderActivities(patientId)
  const setFollowUp = useSetFollowUpAppointment(patientId)

  const changes = [createActivity, updateActivity, archiveActivity, restoreActivity, reorderActivities, setFollowUp]
  const busy = changes.some((change) => change.isPending)
  const failed = changes.find((change) => change.isError)
  // Each change starts by clearing what the last one said, so a failure is
  // never left on screen once a later change has gone through.
  const fresh = () => changes.forEach((change) => change.reset())
  const [showArchived, setShowArchived] = useState(false)
  const archivedQuery = useArchivedRoadmap(patientId, plan.treatment_plan_id, showArchived)

  const headingId = `roadmap-${plan.treatment_plan_id}`
  const roadmap = roadmapQuery.data ? planRoadmap(plan.treatment_plan_id, plan.treatment_goal, roadmapQuery.data, today) : null
  const missed = plan.treatment_goal.filter((goal) => goal.treatment_goal_status === 'missed').length

  return (
    <section aria-labelledby={headingId} className="space-y-4">
      <div className="flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
        <h3 id={headingId} className="text-base font-semibold text-heading">
          Recovery roadmap
        </h3>
        {roadmap ? (
          <p className="text-sm text-muted" data-numeric>
            {roadmap.count.percentage === null
              ? 'No activities yet'
              : `${roadmap.count.percentage}% · ${roadmap.count.done} of ${roadmap.count.total} done`}
            {missed > 0 ? ` · ${missed === 1 ? '1 goal missed' : `${missed} goals missed`}` : ''}
          </p>
        ) : null}
      </div>
      {roadmap && roadmap.count.percentage !== null ? (
        <ProgressBar
          value={roadmap.count.percentage}
          tone="accent"
          label="Roadmap progress"
          valueText={`${roadmap.count.done} of ${roadmap.count.total} done`}
        />
      ) : null}
      <p className="text-xs text-muted">
        Phases are set out automatically: Initial Recovery, one phase for each goal, then Follow-up and Assessment.
        Progress counts the activities the patient marks done and the goals they achieve; doses, appointments and
        check-ins are not counted. A finished roadmap does not complete the plan or discharge the patient.
      </p>

      {failed ? <FormError error={failed.error} title="The roadmap was not changed" /> : null}

      {roadmapQuery.isPending ? (
        <LoadingState label="Loading the roadmap…" />
      ) : roadmapQuery.error ? (
        <ErrorState error={roadmapQuery.error} onRetry={() => void roadmapQuery.refetch()} />
      ) : roadmap ? (
        <>
          <ol className="space-y-4">
            {roadmap.phases.map((item) => (
              <PhaseEditor
                key={item.phase.recovery_phase_id}
                item={item}
                plan={plan}
                busy={busy}
                zone={zone}
                followUp={followUp}
                appointments={appointments}
                onChooseFollowUp={(appointmentId) => {
                  fresh()
                  setFollowUp.mutate({ planId: plan.treatment_plan_id, appointmentId })
                }}
                onAddActivity={(input) => {
                  fresh()
                  return createActivity.mutateAsync({ phaseId: item.phase.recovery_phase_id, ...input })
                }}
                onSaveActivity={(activityId, input) => {
                  fresh()
                  return updateActivity.mutateAsync({ activityId, ...input })
                }}
                onMoveActivity={(activityIndex, by) => {
                  fresh()
                  reorderActivities.mutate({
                    phaseId: item.phase.recovery_phase_id,
                    activityIds: moved(item.activities, activityIndex, by).map(
                      (activity) => activity.recovery_activity_id,
                    ),
                  })
                }}
                onArchiveActivity={(activityId) => {
                  fresh()
                  archiveActivity.mutate(activityId)
                }}
              />
            ))}
          </ol>

          {/* What has been archived, to put back. Read only when opened. */}
          <div className="border-t border-[var(--color-border)] pt-4">
            <Button
              variant="ghost"
              size="sm"
              aria-expanded={showArchived}
              onClick={() => setShowArchived((open) => !open)}
            >
              <Archive aria-hidden="true" />
              {showArchived ? 'Hide archived activities' : 'Show archived activities'}
            </Button>
            {showArchived ? (
              archivedQuery.isPending ? (
                <LoadingState label="Loading what was archived…" />
              ) : archivedQuery.error ? (
                <ErrorState error={archivedQuery.error} onRetry={() => void archivedQuery.refetch()} />
              ) : archivedQuery.data && archivedQuery.data.length > 0 ? (
                <ul className="mt-2 divide-y divide-[var(--color-border)] border-y border-[var(--color-border)]">
                  {archivedQuery.data.map((activity) => (
                    <li
                      key={activity.recovery_activity_id}
                      className="flex flex-col gap-2 py-2.5 sm:flex-row sm:items-center sm:justify-between"
                    >
                      <p className="min-w-0 text-sm text-body">
                        <span className="font-medium">Activity: </span>
                        {activity.recovery_activity_title}
                        <span className="text-muted" data-numeric>
                          {' '}
                          · {activity.recovery_activity_completed_at ? 'done, ' : ''}archived{' '}
                          {formatDate(activity.recovery_activity_archived_at)}
                        </span>
                      </p>
                      <Button
                        variant="secondary"
                        size="sm"
                        disabled={busy}
                        aria-label={`Restore activity ${activity.recovery_activity_title}`}
                        onClick={() => {
                          fresh()
                          restoreActivity.mutate(activity.recovery_activity_id)
                        }}
                      >
                        <RotateCcw aria-hidden="true" />
                        Restore
                      </Button>
                    </li>
                  ))}
                </ul>
              ) : (
                <p className="mt-2 text-sm text-muted">No activity in this plan is archived.</p>
              )
            ) : null}
          </div>
        </>
      ) : null}
    </section>
  )
}

type ActivityInput = { title: string; description: string | null; targetDate: string | null }

function PhaseEditor({
  item,
  plan,
  busy,
  zone,
  followUp,
  appointments,
  onChooseFollowUp,
  onAddActivity,
  onSaveActivity,
  onMoveActivity,
  onArchiveActivity,
}: {
  item: RoadmapPhase
  plan: PlanWithGoals
  busy: boolean
  zone: string
  followUp: AppointmentWithPatient | null | undefined
  appointments: readonly AppointmentWithPatient[]
  onChooseFollowUp: (appointmentId: string | null) => void
  onAddActivity: (input: ActivityInput) => Promise<unknown>
  onSaveActivity: (activityId: string, input: ActivityInput) => Promise<unknown>
  onMoveActivity: (index: number, by: -1 | 1) => void
  onArchiveActivity: (activityId: string) => void
}) {
  const { phase } = item
  const [addingActivity, setAddingActivity] = useState(false)
  const [editingActivityId, setEditingActivityId] = useState<string | null>(null)
  const name = phaseHeading(item)
  const dates = phaseDates(phase.recovery_phase_start_date, phase.recovery_phase_target_end_date)

  return (
    <li className="rounded-[var(--radius-md)] border border-[var(--color-border)] p-4">
      <div className="min-w-0">
        <div className="flex flex-wrap items-center gap-2">
          <h4 className="font-semibold text-heading">
            Phase {item.number} — {name}
          </h4>
          <StatusBadge status={PHASE_STATUS[item.status]} />
        </div>
        <p className="mt-1 text-sm text-muted" data-numeric>
          {[dates, item.count.total === 0 ? 'No activities yet' : `${item.count.done} of ${item.count.total} done`]
            .filter(Boolean)
            .join(' · ')}
        </p>
        <PhaseSubject item={item} followUp={followUp} zone={zone} audience="doctor" />
        {phase.recovery_phase_description ? (
          <p className="mt-1 whitespace-pre-wrap text-sm text-body">{phase.recovery_phase_description}</p>
        ) : null}
        {item.kind === 'follow_up' ? (
          <FollowUpPicker
            key={plan.treatment_plan_follow_up_appointment_id ?? 'none'}
            appointments={appointments}
            chosen={plan.treatment_plan_follow_up_appointment_id}
            zone={zone}
            disabled={busy}
            onChoose={onChooseFollowUp}
          />
        ) : null}
      </div>

      <ul className="mt-3 divide-y divide-[var(--color-border)] border-y border-[var(--color-border)]">
        {item.activities.map((activity, index) =>
          editingActivityId === activity.recovery_activity_id ? (
            <li key={activity.recovery_activity_id} className="py-3">
              <ActivityForm
                plan={plan}
                activity={activity}
                submitLabel="Save activity"
                onCancel={() => setEditingActivityId(null)}
                onSubmit={async (input) => {
                  await onSaveActivity(activity.recovery_activity_id, input)
                  setEditingActivityId(null)
                }}
              />
            </li>
          ) : (
            <ActivityRow
              key={activity.recovery_activity_id}
              activity={activity}
              isFirst={index === 0}
              isLast={index === item.activities.length - 1}
              busy={busy}
              onEdit={() => setEditingActivityId(activity.recovery_activity_id)}
              onMove={(by) => onMoveActivity(index, by)}
              onArchive={() => onArchiveActivity(activity.recovery_activity_id)}
            />
          ),
        )}
        {item.activities.length === 0 ? <li className="py-3 text-sm text-muted">No activities yet</li> : null}
      </ul>

      <div className="mt-3">
        {addingActivity ? (
          <ActivityForm
            plan={plan}
            submitLabel="Add activity"
            onCancel={() => setAddingActivity(false)}
            onSubmit={async (input) => {
              await onAddActivity(input)
              setAddingActivity(false)
            }}
          />
        ) : (
          <Button variant="secondary" size="sm" onClick={() => setAddingActivity(true)} aria-label={`Add activity to ${name}`}>
            <ListPlus aria-hidden="true" />
            Add activity
          </Button>
        )}
      </div>
    </li>
  )
}

/**
 * The plan's follow-up appointment, chosen from the patient's own
 * appointments - none is ever picked for the doctor. A past or cancelled
 * one stays listed only while it is the one chosen.
 */
function FollowUpPicker({
  appointments,
  chosen,
  zone,
  disabled,
  onChoose,
}: {
  appointments: readonly AppointmentWithPatient[]
  chosen: string | null
  zone: string
  disabled: boolean
  onChoose: (appointmentId: string | null) => void
}) {
  const [value, setValue] = useState(chosen ?? '')
  const options = [...appointments]
    .filter(
      (appointment) =>
        appointment.appointment_id === chosen ||
        appointment.appointment_status === 'scheduled' ||
        appointment.appointment_status === 'confirmed',
    )
    .sort((a, b) => a.appointment_date.localeCompare(b.appointment_date))
  const label = (appointment: AppointmentWithPatient) => {
    const at = zonedDayAndTime(appointment.appointment_date, zone)
    const when = at ? `${formatDate(at.day)}, ${at.time}` : formatDate(appointment.appointment_date)
    return `${when} · ${appointmentStatus[appointment.appointment_status].label}`
  }
  return (
    <form
      className="mt-3 flex flex-col gap-2 sm:flex-row sm:items-end"
      onSubmit={(event) => {
        event.preventDefault()
        onChoose(value || null)
      }}
    >
      <Field label="Follow-up appointment" className="min-w-0 flex-1">
        <Select value={value} onChange={(event) => setValue(event.target.value)} className="h-9 text-sm">
          <option value="">None chosen</option>
          {options.map((appointment) => (
            <option key={appointment.appointment_id} value={appointment.appointment_id}>
              {label(appointment)}
            </option>
          ))}
        </Select>
      </Field>
      <Button type="submit" variant="secondary" size="sm" disabled={disabled || value === (chosen ?? '')}>
        <CalendarClock aria-hidden="true" />
        Save follow-up
      </Button>
    </form>
  )
}

function ActivityRow({
  activity,
  isFirst,
  isLast,
  busy,
  onEdit,
  onMove,
  onArchive,
}: {
  activity: RecoveryActivity
  isFirst: boolean
  isLast: boolean
  busy: boolean
  onEdit: () => void
  onMove: (by: -1 | 1) => void
  onArchive: () => void
}) {
  const done = activity.recovery_activity_completed_at !== null
  const name = activity.recovery_activity_title
  const [confirmingArchive, setConfirmingArchive] = useState(false)
  return (
    <li className="py-3">
      <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
      <div className="flex min-w-0 gap-3">
        {done ? (
          <Check className="mt-0.5 size-5 shrink-0 text-success-700" aria-hidden="true" />
        ) : (
          <CircleDashed className="mt-0.5 size-5 shrink-0 text-neutral-500" aria-hidden="true" />
        )}
        <div className="min-w-0">
          <p className="text-body">{name}</p>
          {activity.recovery_activity_description ? (
            <p className="mt-0.5 whitespace-pre-wrap text-sm text-muted">{activity.recovery_activity_description}</p>
          ) : null}
          <p className={cn('mt-0.5 text-sm', done ? 'text-success-700' : 'text-muted')} data-numeric>
            {done
              ? `Done by the patient on ${formatDate(activity.recovery_activity_completed_at)}`
              : `Not done yet${activity.recovery_activity_target_date ? ` · by ${formatDate(activity.recovery_activity_target_date)}` : ''}`}
          </p>
        </div>
      </div>
      <div className="flex flex-wrap gap-1 sm:shrink-0">
        <Button variant="ghost" size="sm" onClick={onEdit} aria-label={`Edit activity ${name}`}>
          <Pencil aria-hidden="true" />
          Edit
        </Button>
        <Button variant="ghost" size="sm" disabled={isFirst || busy} onClick={() => onMove(-1)} aria-label={`Move activity ${name} up`}>
          <ArrowUp aria-hidden="true" />
        </Button>
        <Button variant="ghost" size="sm" disabled={isLast || busy} onClick={() => onMove(1)} aria-label={`Move activity ${name} down`}>
          <ArrowDown aria-hidden="true" />
        </Button>
        <Button
          variant="ghost"
          size="sm"
          disabled={busy}
          onClick={() => setConfirmingArchive(true)}
          aria-label={`Archive activity ${name}`}
        >
          <Archive aria-hidden="true" />
        </Button>
      </div>
      </div>
      {confirmingArchive ? (
        <div className="mt-2 rounded-[var(--radius-sm)] bg-warning-50 p-3 text-sm text-body">
          <p>
            Archive “{name}”? It leaves the patient’s roadmap{done ? '; that they did it stays on record' : ''}. It can
            be restored from the archived list.
          </p>
          <div className="mt-2 flex gap-2">
            <Button
              variant="danger"
              size="sm"
              onClick={() => {
                setConfirmingArchive(false)
                onArchive()
              }}
            >
              Archive activity
            </Button>
            <Button variant="ghost" size="sm" onClick={() => setConfirmingArchive(false)}>
              Keep it
            </Button>
          </div>
        </div>
      ) : null}
    </li>
  )
}

/** Whether a date lies inside the plan's own dates, as the database checks. */
function outsidePlan(plan: PlanWithGoals, date: string | null): boolean {
  if (!date) return false
  return date < plan.treatment_plan_start_date || (plan.treatment_plan_end_date !== null && date > plan.treatment_plan_end_date)
}

function planRange(plan: PlanWithGoals): string {
  return plan.treatment_plan_end_date
    ? `${formatDate(plan.treatment_plan_start_date)} and ${formatDate(plan.treatment_plan_end_date)}`
    : `${formatDate(plan.treatment_plan_start_date)} or later`
}

function ActivityForm({
  plan,
  activity,
  submitLabel,
  onSubmit,
  onCancel,
}: {
  plan: PlanWithGoals
  activity?: RecoveryActivity
  submitLabel: string
  onSubmit: (input: ActivityInput) => Promise<void>
  onCancel: () => void
}) {
  const [title, setTitle] = useState(activity?.recovery_activity_title ?? '')
  const [description, setDescription] = useState(activity?.recovery_activity_description ?? '')
  const [target, setTarget] = useState(activity?.recovery_activity_target_date ?? '')
  const [problems, setProblems] = useState<{ title?: string; target?: string }>({})
  const [saving, setSaving] = useState(false)

  const submit = async (event: FormEvent) => {
    event.preventDefault()
    const next: typeof problems = {}
    if (!title.trim()) next.title = 'Enter what the patient should do.'
    if (outsidePlan(plan, target || null)) next.target = `Choose a date between ${planRange(plan)}.`
    setProblems(next)
    if (Object.keys(next).length > 0 || saving) return
    setSaving(true)
    try {
      await onSubmit({ title: title.trim(), description: description.trim() || null, targetDate: target || null })
    } catch {
      // Shown above the roadmap, from the mutation; the form keeps what was typed.
    } finally {
      setSaving(false)
    }
  }

  return (
    <form noValidate onSubmit={(event) => void submit(event)} className="space-y-3" aria-label={submitLabel}>
      <Field label="Activity" required error={problems.title}>
        <Input value={title} maxLength={200} onChange={(event) => setTitle(event.target.value)} />
      </Field>
      <Field label="Instructions">
        <Textarea value={description} maxLength={2000} rows={2} onChange={(event) => setDescription(event.target.value)} />
      </Field>
      <Field label="Target date" error={problems.target}>
        <Input type="date" value={target} onChange={(event) => setTarget(event.target.value)} />
      </Field>
      <div className="flex gap-2">
        <Button type="submit" size="sm" isLoading={saving} loadingLabel="Saving…">
          {submitLabel}
        </Button>
        <Button type="button" variant="ghost" size="sm" onClick={onCancel}>
          Cancel
        </Button>
      </div>
    </form>
  )
}
